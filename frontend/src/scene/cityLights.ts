let cached: THREE.CanvasTexture | null = null;

export function cityLightsTexture(): THREE.CanvasTexture {
  if (cached) return cached;
  const W = 4096, H = 2048;
  const c = document.createElement("canvas");
  c.width = W; c.height = H;
  const g = c.getContext("2d")!;
  g.fillStyle = "#000";
  g.fillRect(0, 0, W, H);
  g.globalCompositeOperation = "lighter";
  // deterministic jitter to break up perfect dots into small clusters
  let seed = 11;
  const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);
  for (const [lat, lon, w] of METROS) {
    const x = ((lon + 180) / 360) * W;
    const y = ((90 - lat) / 180) * H;
    const blobs = 4 + Math.round(w * 8);
    for (let k = 0; k < blobs; k++) {
      const r = (1.2 + w * 3.6) * (0.5 + rnd());
      const spread = 3 + w * 11;
      const ox = (rnd() - 0.5) * spread, oy = (rnd() - 0.5) * spread * 0.7;
      const grad = g.createRadialGradient(x + ox, y + oy, 0, x + ox, y + oy, r);
      const a = 0.22 + 0.4 * w;
      grad.addColorStop(0, `rgba(255,255,255,${a})`);
      grad.addColorStop(1, "rgba(255,255,255,0)");
      g.fillStyle = grad;
      g.fillRect(x + ox - r, y + oy - r, 2 * r, 2 * r);
    }
  }
  const tex = new THREE.CanvasTexture(c);
  tex.colorSpace = THREE.NoColorSpace;
  tex.wrapS = THREE.RepeatWrapping;
  cached = tex;
  return tex;
}
